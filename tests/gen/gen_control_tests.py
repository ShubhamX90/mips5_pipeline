#!/usr/bin/env python3
"""Generates the control-flow matrix (18) and the data-hazard matrix (38).

18_branch_matrix  every conditional branch x boundary operand pairs, forward and
                  backward targets; the fall-through path holds a marker write and
                  a store that must be squashed when the branch is taken.
38_hazard_matrix  {ALU, LOAD} producer x distance 0..4 x 9 consumer kinds
                  (alu rs / rt / both, store data / address, load address,
                  branch rs / rt, jr).  Every cell self-checks.

Expected values come from independent Python arithmetic.
Run from the repository root:  python3 tests/gen/gen_control_tests.py
"""
from pathlib import Path

M = 0xFFFFFFFF
OUT = Path(__file__).resolve().parents[1] / "asm"


def s32(v):
    v &= M
    return v - (1 << 32) if v >> 31 else v


# ---------------------------------------------------------------------------- 18
def branch_matrix():
    L = ["# 18_branch_matrix -- every conditional branch x boundary operands, forward and backward.",
         "# Operands are produced by the two instructions immediately before the branch, so the",
         "# comparison also exercises EX/MEM and MEM/WB forwarding into the branch unit.",
         "# The fall-through path writes a marker register and memory; it is wrong-path when the",
         "# branch is taken and must leave no trace.",
         "# Generated by tests/gen/gen_control_tests.py; expectations from independent Python.",
         ".text"]
    two = {"beq": lambda a, b: a == b, "bne": lambda a, b: a != b}
    one = {"blez": lambda a: s32(a) <= 0, "bgtz": lambda a: s32(a) > 0,
           "bltz": lambda a: s32(a) < 0, "bgez": lambda a: s32(a) >= 0}
    pairs = [(0, 0), (1, 1), (1, 2), (M, M), (M, 1), (0x7FFFFFFF, 0x80000000), (0x80000000, 0x80000000), (0, 5)]
    vals = [0, 1, M, 0x7FFFFFFF, 0x80000000, 2, (-2) & M]
    cid = 0
    cases = []
    for op, f in two.items():
        for a, b in pairs:
            cases.append((op, a, b, f(a, b)))
    for op, f in one.items():
        for a in vals:
            cases.append((op, a, None, f(a)))
    for n, (op, a, b, taken) in enumerate(cases):
        cid += 1
        for direction in ("fwd", "bwd"):
            tag = f"{n}{direction[0]}"
            ops = f"$s0, $s1" if b is not None else "$s0"
            L.append(f"    li $s5, 0")
            if direction == "bwd":
                L.append(f"    j fwd_{tag}")
                L.append(f"back_{tag}:")
                L.append(f"    li $s5, 7")
                L.append(f"    j after_{tag}")
                L.append(f"fwd_{tag}:")
            L.append(f"    li $s0, {s32(a)}")
            if b is not None:
                L.append(f"    li $s1, {s32(b)}")
            tgt = f"T_{tag}" if direction == "fwd" else f"back_{tag}"
            L.append(f"    {op} {ops}, {tgt}")
            L.append(f"    li $s5, 1              # fall-through marker (wrong path if taken)")
            L.append(f"    sw $s5, 200($zero)     # wrong-path store")
            L.append(f"    li $s4, 99")
            if direction == "bwd":
                L.append(f"    j after_{tag}")
            L.append(f"T_{tag}:" if direction == "fwd" else f"after_{tag}:")
            exp = (0 if direction == "fwd" else 7) if taken else 1
            L.append(f"    check $s5, {exp}, {cid * 2 - (1 if direction == 'fwd' else 0)}")
    L.append(".endtest")
    (OUT / "18_branch_matrix.s").write_text("\n".join(L) + "\n")
    print(f"wrote 18_branch_matrix.s: {len(cases) * 2} cells")


# ---------------------------------------------------------------------------- 38
def hazard_matrix():
    consumers = ["alu_rs", "alu_rt", "alu_both", "store_data", "store_addr",
                 "load_addr", "branch_rs", "branch_rt", "jr", "mul"]
    regs = ["$t0", "$t1", "$t2", "$t3", "$t4", "$t5", "$t6", "$t7"]
    L = ["# 38_hazard_matrix -- {ALU, LOAD} producer x distance 0..4 x consumer kind.",
         "# distance = number of independent instructions between producer and consumer.",
         "# Before each cell the target register is reset to 0 well in advance, so a",
         "# missed forward/bypass/stall reads a recognisably stale value and the check fails.",
         "# Generated by tests/gen/gen_control_tests.py; expectations from independent Python.",
         ".text",
         "    li $t8, 0xBEEF"]
    data = []
    cid = 0
    cell = 0
    for prod in ("alu", "load"):
        for dist in range(5):
            for cons in consumers:
                cell += 1
                cid += 1
                rx = regs[cell % len(regs)]
                # value semantics per consumer kind
                if cons in ("store_addr", "load_addr"):
                    V = 512 + 4 * (cell % 60)       # a valid, aligned data address
                elif cons == "jr":
                    V = None                        # label address
                else:
                    V = 0x100 + cell * 7            # small positive: fits addiu
                tag = f"c{cell}"
                if cons == "jr":
                    prodval = f"jt_{tag}" if prod == "load" else f"Tj_{tag}"
                else:
                    prodval = str(V)
                L.append(f"    # cell {cell}: producer={prod} dist={dist} consumer={cons}")
                L.append(f"    li {rx}, 0")
                if cons in ("branch_rs", "branch_rt", "jr"):
                    L.append("    li $s1, 0                 # outcome marker, set early so the dependence distance stays exact")
                L.append("    nop"); L.append("    nop"); L.append("    nop"); L.append("    nop")
                if prod == "alu":
                    L.append(f"    addiu {rx}, $zero, {prodval}")
                else:
                    L.append(f"    lw {rx}, d_{tag}($zero)")
                    data.append(f"d_{tag}: .word {V if V is not None else 'Tj_' + tag}")
                for k in range(dist):
                    L.append(f"    addiu $t9, $zero, {k + 1}")
                if cons == "alu_rs":
                    L += [f"    addu $s1, {rx}, $zero"]; exp = V
                elif cons == "alu_rt":
                    L += [f"    addu $s1, $zero, {rx}"]; exp = V
                elif cons == "alu_both":
                    L += [f"    addu $s1, {rx}, {rx}"]; exp = 2 * V
                elif cons == "store_data":
                    L += [f"    sw {rx}, 300($zero)", "    lw $s1, 300($zero)"]; exp = V
                elif cons == "store_addr":
                    L += [f"    sw $t8, 0({rx})", f"    lw $s1, {V}($zero)"]; exp = 0xBEEF
                elif cons == "load_addr":
                    L += [f"    lw $s1, 0({rx})"]; exp = 0xC0DE0000 + (V - 512) // 4
                elif cons == "branch_rs":
                    L += [f"    bne {rx}, $zero, T_{tag}", "    li $s1, 1", f"T_{tag}:"]; exp = 0
                elif cons == "branch_rt":
                    L += [f"    beq $zero, {rx}, T_{tag}", "    li $s1, 1", f"T_{tag}:"]; exp = 1
                elif cons == "jr":
                    L += [f"    jr {rx}", "    li $s1, 1", f"Tj_{tag}:"]; exp = 0
                elif cons == "mul":
                    L += [f"    mul $s1, {rx}, {rx}"]; exp = (V * V) & M
                L.append(f"    check $s1, {s32(exp)}, {cid}")
    L.append(".endtest")
    L.append(".data")
    L += data
    L.append(".org 512")
    for i in range(64):
        L.append(f".word {0xC0DE0000 + i}")
    (OUT / "38_hazard_matrix.s").write_text("\n".join(L) + "\n")
    print(f"wrote 38_hazard_matrix.s: {cell} cells")


if __name__ == "__main__":
    branch_matrix()
    hazard_matrix()
