#!/usr/bin/env python3
"""Generates the exhaustive-ish datapath directed tests (01-04, 16).

Every expected value is computed here with plain Python integer arithmetic
written directly from the MIPS32 manual -- it shares no code with tools/iss.py
or the RTL, so the generated programs are an independent oracle for both
(each program checks its own results in-line via the `check` macro).

Run from the repository root:  python3 tests/gen/gen_datapath_tests.py
"""
from pathlib import Path

M = 0xFFFFFFFF
OUT = Path(__file__).resolve().parents[1] / "asm"


def s32(v):
    v &= M
    return v - (1 << 32) if v >> 31 else v


def sx16(v):
    v &= 0xFFFF
    return v - 0x10000 if v & 0x8000 else v


class Prog:
    def __init__(self, title, desc):
        self.lines = [f"# {title}", *[f"# {d}" for d in desc.splitlines()],
                      "# Generated by tests/gen/gen_datapath_tests.py; expected values come from",
                      "# independent Python arithmetic.  Do not edit by hand.", ".text"]
        self.cid = 0
        self.data = []

    def emit(self, s):
        self.lines.append("    " + s)

    def check(self, reg, exp):
        self.cid += 1
        self.emit(f"check {reg}, {s32(exp)}, {self.cid}")

    def label(self, s):
        self.lines.append(f"{s}:")

    def text(self):
        out = list(self.lines)
        out.append(".endtest")
        if self.data:
            out.append(".data")
            out += self.data
        return "\n".join(out) + "\n"


def write(name, prog):
    (OUT / name).write_text(prog.text())
    print(f"wrote {name}: {prog.cid} checks")


# ------------------------------------------------------------------------------ 01
def alu_basic():
    p = Prog("01_alu_basic", "Register-register ALU ops over boundary operand pairs\n"
             "(add/addu/sub/subu/and/or/xor/nor/slt/sltu).")
    pairs = [(0, 0), (1, 1), (M, 1), (0x7FFFFFFF, 1), (0x80000000, 0x80000000),
             (0x12345678, 0x9ABCDEF0), (0xF0F0F0F0, 0x0FF00FF0), (5, (-3) & M),
             (0x80000000, 1), (0, M)]
    ops = {
        "add": lambda a, b: a + b, "addu": lambda a, b: a + b,
        "sub": lambda a, b: a - b, "subu": lambda a, b: a - b,
        "and": lambda a, b: a & b, "or": lambda a, b: a | b,
        "xor": lambda a, b: a ^ b, "nor": lambda a, b: ~(a | b),
        "slt": lambda a, b: int(s32(a) < s32(b)), "sltu": lambda a, b: int(a < b),
    }
    for a, b in pairs:
        p.emit(f"li $s0, {s32(a)}")
        p.emit(f"li $s1, {s32(b)}")
        for op, f in ops.items():
            p.emit(f"{op} $t0, $s0, $s1")
            p.check("$t0", f(a, b) & M)
    write("01_alu_basic.s", p)


# ------------------------------------------------------------------------------ 02
def alu_imm():
    p = Prog("02_alu_imm", "Immediate ALU ops: sign extension (addi/addiu/slti/sltiu) vs zero\n"
             "extension (andi/ori/xori), lui.")
    vals = [0, 1, 0x7FFFFFFF, 0x80000000, M, 0x12345678, 0x0000FFFF]
    simms = [0, 1, -1, 0x7FFF, -32768, 100, -100]
    uimms = [0, 1, 0x7FFF, 0x8000, 0xFFFF, 0x00FF, 0xFF00]
    for v in vals:
        p.emit(f"li $s0, {s32(v)}")
        for i in simms:
            p.emit(f"addi  $t0, $s0, {i}");  p.check("$t0", v + i)
            p.emit(f"addiu $t0, $s0, {i}");  p.check("$t0", v + i)
            p.emit(f"slti  $t0, $s0, {i}");  p.check("$t0", int(s32(v) < i))
            p.emit(f"sltiu $t0, $s0, {i}");  p.check("$t0", int(v < (i & M)))
        for i in uimms:
            p.emit(f"andi  $t0, $s0, {i}");  p.check("$t0", v & i)
            p.emit(f"ori   $t0, $s0, {i}");  p.check("$t0", v | i)
            p.emit(f"xori  $t0, $s0, {i}");  p.check("$t0", v ^ i)
    for i in uimms:
        p.emit(f"lui $t0, {i}")
        p.check("$t0", (i << 16) & M)
    write("02_alu_imm.s", p)


# ------------------------------------------------------------------------------ 03
def shifts():
    p = Prog("03_shifts", "Immediate and variable shifts incl. shift by 0/31, arithmetic shift of\n"
             "negative values, and variable amounts >= 32 (only the low 5 bits count).")
    vals = [1, 0x80000001, 0x7FFFFFFF, 0xDEADBEEF, M, 0x00010000]
    for v in vals:
        p.emit(f"li $s0, {s32(v)}")
        for sh in (0, 1, 4, 15, 16, 31):
            p.emit(f"sll $t0, $s0, {sh}"); p.check("$t0", (v << sh) & M)
            p.emit(f"srl $t0, $s0, {sh}"); p.check("$t0", v >> sh)
            p.emit(f"sra $t0, $s0, {sh}"); p.check("$t0", (s32(v) >> sh) & M)
        for amt in (0, 1, 7, 31, 32, 33, 0xFFE5):
            p.emit(f"li $s1, {amt}")
            a5 = amt & 31
            p.emit("sllv $t0, $s0, $s1"); p.check("$t0", (v << a5) & M)
            p.emit("srlv $t0, $s0, $s1"); p.check("$t0", v >> a5)
            p.emit("srav $t0, $s0, $s1"); p.check("$t0", (s32(v) >> a5) & M)
    write("03_shifts.s", p)


# ------------------------------------------------------------------------------ 04
def mul():
    p = Prog("04_mul", "SPECIAL2 MUL (low 32 bits of the product), signed/unsigned corner cases.")
    pairs = [(0, 0), (1, 1), (3, 7), (M, M), (M, 5), (0x10000, 0x10000), (0x7FFFFFFF, 2),
             (0x80000000, 0x80000000), (0x12345678, 0x9ABCDEF0), (123456, (-789) & M),
             (0xFFFF, 0xFFFF), (0x80000000, M)]
    for a, b in pairs:
        p.emit(f"li $s0, {s32(a)}")
        p.emit(f"li $s1, {s32(b)}")
        p.emit("mul $t0, $s0, $s1");  p.check("$t0", (a * b) & M)
        p.emit("mul $t0, $s1, $s0");  p.check("$t0", (a * b) & M)
    # dependent multiplies: result forwarded straight into the next multiply
    p.emit("li $t1, 3")
    p.emit("mul $t1, $t1, $t1")
    p.emit("mul $t1, $t1, $t1")
    p.emit("mul $t1, $t1, $t1")
    p.check("$t1", pow(3, 8) & M)
    write("04_mul.s", p)


# ------------------------------------------------------------------------------ 16
def mem_subword():
    p = Prog("16_mem_subword", "Byte/half loads (sign vs zero extension) at every alignment and byte/half\n"
             "stores merging into a word at every alignment.")
    src = 0x80817F01
    mem = src.to_bytes(4, "little")
    p.emit("lw $s0, src($zero)")
    p.check("$s0", src)
    for off in range(4):
        b = mem[off]
        p.emit(f"lb  $t0, {off}($zero)");  p.check("$t0", b - 256 if b & 0x80 else b)
        p.emit(f"lbu $t0, {off}($zero)");  p.check("$t0", b)
    for off in (0, 2):
        h = int.from_bytes(mem[off:off + 2], "little")
        p.emit(f"lh  $t0, {off}($zero)");  p.check("$t0", sx16(h))
        p.emit(f"lhu $t0, {off}($zero)");  p.check("$t0", h)
    # loads whose address comes from a just-computed register (forwarded base)
    p.emit("addiu $s1, $zero, 2")
    p.emit("lb $t0, 1($s1)");   p.check("$t0", mem[3] - 256 if mem[3] & 0x80 else mem[3])
    # sb into every lane of a zeroed word then read the word back
    dst = bytearray(4)
    for off, val in enumerate((0xAA, 0xBB, 0xCC, 0xDD)):
        p.emit(f"li $t1, {val | 0x12340000}")      # upper bits must be ignored by sb
        p.emit(f"sb $t1, {16 + off}($zero)")
        dst[off] = val
    p.emit("lw $t0, 16($zero)");  p.check("$t0", int.from_bytes(dst, "little"))
    # sh into both halves of another word
    dst = bytearray(4)
    p.emit("li $t1, 0x1234ABCD");  p.emit("sh $t1, 24($zero)");  dst[0:2] = (0xABCD).to_bytes(2, "little")
    p.emit("li $t1, 0x5678EF01");  p.emit("sh $t1, 26($zero)");  dst[2:4] = (0xEF01).to_bytes(2, "little")
    p.emit("lw $t0, 24($zero)");  p.check("$t0", int.from_bytes(dst, "little"))
    # sub-word store must not disturb neighbouring bytes
    p.emit("li $t1, -1");  p.emit("sw $t1, 32($zero)")
    p.emit("sb $zero, 33($zero)")
    p.emit("lw $t0, 32($zero)");  p.check("$t0", 0xFFFF00FF)
    p.emit("sh $zero, 34($zero)")
    p.emit("lw $t0, 32($zero)");  p.check("$t0", 0x0000_00FF)
    # store-then-load of the same byte back to back (store in MEM while load in EX)
    p.emit("li $t1, 0x7F")
    p.emit("sb $t1, 40($zero)")
    p.emit("lbu $t2, 40($zero)")
    p.check("$t2", 0x7F)
    p.emit("li $t1, 0x80")
    p.emit("sb $t1, 41($zero)")
    p.emit("lb $t2, 41($zero)")
    p.check("$t2", -128)
    p.data = ["src: .word 0x80817F01", ".align 4", ".space 60"]
    write("16_mem_subword.s", p)


if __name__ == "__main__":
    alu_basic()
    alu_imm()
    shifts()
    mul()
    mem_subword()
